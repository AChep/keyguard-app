package com.artemchep.keyguard.buildplugins.cargo

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder

class CargoWorkspaceVersionTest {
    @get:Rule
    val temporaryFolder = TemporaryFolder()

    private val root get() = temporaryFolder.root

    private val external =
        """

        [[package]]
        name = "core"
        version = "0.1.0"
        source = "registry+https://github.com/rust-lang/crates.io-index"
        checksum = "unchanged"
        """.trimIndent() + "\n"

    @Before
    fun setUp() {
        write(
            "Cargo.toml",
            """
            [workspace]
            members = [
                # A "commented" member is not a member.
                "crates/*",
            ]

            # Keep this comment.
            [workspace.package]
            version = "0.1.0" # app

            [workspace.dependencies]
            external = "0.1.0"
            """.trimIndent() + "\n",
        )
        write("crates/agent/Cargo.toml", "[package]\nname = \"agent\"\nversion.workspace = true\n")
        write("crates/core/Cargo.toml", "[package]\nname = \"core\"\nversion = { workspace = true }\n")
        write(
            "Cargo.lock",
            """
            # Generated by Cargo.
            version = 4

            [[package]]
            name = "agent"
            version = "0.1.0"
            dependencies = ["core 0.1.0"]

            [[package]]
            name = "core"
            version = "0.1.0"
            dependencies = [
             "core 0.1.0 (registry+https://github.com/rust-lang/crates.io-index)",
            ]
            """.trimIndent() + "\n" + external,
        )
    }

    @Test
    fun `reports stale files without writing`() {
        val before = snapshot()
        val updates = cargoWorkspaceVersionUpdates(root, "3.4.0")
        assertEquals(setOf("Cargo.toml", "Cargo.lock"), updates.keys)
        assertEquals(before, snapshot())
    }

    @Test
    fun `updates workspace packages and keeps dependency pins`() {
        generate("3.4.0")
        assertEquals(emptyMap<String, String>(), cargoWorkspaceVersionUpdates(root, "3.4.0"))
        val manifest = read("Cargo.toml")
        assertTrue(manifest.contains("version = \"3.4.0\" # app"))
        assertTrue(manifest.contains("# Keep this comment."))
        assertTrue(manifest.contains("external = \"0.1.0\""))
        val lock = read("Cargo.lock")
        assertTrue(lock.contains(external))
        assertTrue(lock.contains("\"core 0.1.0 (registry+"))
        assertTrue(lock.contains("dependencies = [\"core 3.4.0\"]"))
        assertEquals(2, Regex("version = \"3\\.4\\.0\"").findAll(lock).count())

        val before = snapshot()
        generate("3.4.0")
        assertEquals(before, snapshot())
    }

    @Test
    fun `detects a later bump and lockfile-only drift`() {
        generate("3.4.0")
        assertTrue(cargoWorkspaceVersionUpdates(root, "3.5.0").isNotEmpty())
        generate("3.5.0")
        assertEquals(emptyMap<String, String>(), cargoWorkspaceVersionUpdates(root, "3.5.0"))
        write("Cargo.lock", read("Cargo.lock").replace("version = \"3.5.0\"", "version = \"3.4.0\""))
        assertEquals(setOf("Cargo.lock"), cargoWorkspaceVersionUpdates(root, "3.5.0").keys)
    }

    @Test
    fun `member cannot stop inheriting the workspace version`() {
        write("crates/core/Cargo.toml", "[package]\nname = \"core\"\nversion = \"0.1.0\"\n")
        val e = assertThrows(IllegalStateException::class.java) {
            cargoWorkspaceVersionUpdates(root, "3.4.0")
        }
        assertEquals("crates/core/Cargo.toml must use version.workspace = true.", e.message)
    }

    @Test
    fun `rejects versions that are not major minor patch`() {
        listOf("03.4.0", "3.4", "3.4.0-beta").forEach { version ->
            assertThrows(IllegalArgumentException::class.java) {
                cargoWorkspaceVersionUpdates(root, version)
            }
        }
    }

    @Test
    fun `errors name the file`() {
        write("Cargo.lock", "version = 4\n$external")
        val missing = assertThrows(IllegalStateException::class.java) {
            cargoWorkspaceVersionUpdates(root, "3.4.0")
        }
        assertEquals("Cargo.lock: missing workspace packages: agent, core.", missing.message)

        write("Cargo.toml", "[workspace]\nmembers = [\"crates/*\"]\n")
        val table = assertThrows(IllegalStateException::class.java) {
            cargoWorkspaceVersionUpdates(root, "3.4.0")
        }
        assertEquals("Cargo.toml: expected one [workspace.package] table, found 0.", table.message)
    }

    @Test
    fun `skips files that match a member pattern`() {
        write("crates/.DS_Store", "")
        generate("3.4.0")
        assertEquals(emptyMap<String, String>(), cargoWorkspaceVersionUpdates(root, "3.4.0"))
    }

    @Test
    fun `trailing lockfile tables stay outside package blocks`() {
        write(
            "Cargo.lock",
            read("Cargo.lock").replace(external, "") +
                "\n[[patch.unused]]\nname = \"core\"\nversion = \"9.9.9\"\n",
        )
        generate("3.4.0")
        assertTrue(read("Cargo.lock").contains("[[patch.unused]]\nname = \"core\"\nversion = \"9.9.9\"\n"))
    }

    @Test
    fun `preserves windows line endings`() {
        snapshot().forEach { (path, content) -> write(path, content.replace("\n", "\r\n")) }
        generate("3.4.0")
        snapshot().forEach { (path, content) ->
            assertFalse(path, content.replace("\r\n", "").contains('\n'))
        }
        assertEquals(emptyMap<String, String>(), cargoWorkspaceVersionUpdates(root, "3.4.0"))
    }

    private fun generate(version: String) {
        writeCargoWorkspaceVersionUpdates(root, cargoWorkspaceVersionUpdates(root, version))
    }

    private fun write(
        path: String,
        content: String,
    ) {
        root.resolve(path).apply { parentFile.mkdirs() }.writeText(content)
    }

    private fun read(path: String) = root.resolve(path).readText()

    private fun snapshot() = root.walkTopDown()
        .filter { it.isFile }
        .associate { it.relativeTo(root).invariantSeparatorsPath to it.readText() }
}
