package com.artemchep.keyguard.common.service.sshagent.bookmarks

import com.artemchep.keyguard.common.service.crypto.SSH_CERTIFICATE_FILE_SUFFIX

const val SSH_BOOKMARKS_CONFIG_FILE_NAME = "config"

/**
 * The start of a configuration that Keyguard wrote. Keyguard removes
 * only a configuration that starts with it, so never change it.
 */
const val SSH_BOOKMARKS_CONFIG_MARKER = "# Generated by Keyguard"

private val SSH_BOOKMARKS_CONFIG_HEADER = """
    $SSH_BOOKMARKS_CONFIG_MARKER from the ssh:// fields of SSH key items.
    # Keyguard replaces this file, so edit the items instead.
""".trimIndent()

/** The key that the agent offers to a bookmarked host. */
data class SshBookmarkIdentity(
    /** The lowercase hex SHA-256 of the public key blob; names the key file. */
    val keySha256: String,
    /** The OpenSSH public key, without a comment. */
    val publicKey: String,
    val certificate: SshBookmarkCertificate? = null,
)

data class SshBookmarkCertificate(
    /** The lowercase hex SHA-256 of the certificate blob; names its file. */
    val sha256: String,
    /** The OpenSSH user certificate of the key, without a comment. */
    val certificate: String,
)

data class SshBookmarkEntry(
    val bookmark: SshBookmark,
    val identity: SshBookmarkIdentity,
    /** Orders the keys of one host, for example by the name of the item. */
    val sortKey: String,
)

data class SshBookmarksConfig(
    /** The contents of each generated file, by file name. */
    val files: Map<String, String>,
    val summary: SshBookmarksSummary,
)

/**
 * Renders an SSH configuration that pins each bookmarked host to its keys,
 * plus the public key and certificate files that it points to.
 *
 * A block with `IdentitiesOnly` but without an `IdentityFile` would disable
 * every key for its host, so a host without a key gets no block.
 *
 * @param directory the generated directory, as OpenSSH should read it,
 * for example `~/.ssh/keyguard`.
 * @param identityAgent the socket or the named pipe of the agent, or `null`
 * to leave the agent to the rest of the configuration.
 */
fun renderSshBookmarksConfig(
    entries: List<SshBookmarkEntry>,
    skipped: Int,
    directory: String,
    identityAgent: String?,
): SshBookmarksConfig {
    val directoryPath = requireNotNull(sshConfigPathOrNull(directory)) {
        "SSH configuration can not refer to the directory: $directory"
    }.removeSuffix("/")
    val identityAgentPath = identityAgent?.let(::sshConfigPathOrNull)

    val files = mutableMapOf<String, String>()
    val blocks = entries
        // A block matches a host and a user, on any port.
        .groupBy { entry -> entry.bookmark.copy(port = null) }
        .toList()
        // The block of a user goes first, so that its keys
        // are offered before the keys of any user.
        .sortedWith(
            compareBy(
                { (key, _) -> key.host },
                { (key, _) -> key.user == null },
                { (key, _) -> key.user },
            ),
        )
    val config = buildString {
        appendLine(SSH_BOOKMARKS_CONFIG_HEADER)
        blocks.forEach { (key, blockEntries) ->
            val identities = blockEntries
                .sortedWith(
                    compareBy(
                        { it.sortKey },
                        { it.identity.keySha256 },
                    ),
                )
                .map { it.identity }
            appendLine()
            appendSshBookmarkBlock(
                key = key,
                // Items may share a key, but only some of them
                // have a certificate, so keep every certificate.
                identities = identities.distinctBy { it.keySha256 },
                certificates = identities
                    .mapNotNull { it.certificate }
                    .distinctBy { it.sha256 },
                directoryPath = directoryPath,
                identityAgentPath = identityAgentPath,
                files = files,
            )
        }
    }
    files[SSH_BOOKMARKS_CONFIG_FILE_NAME] = config
    return SshBookmarksConfig(
        files = files,
        summary = SshBookmarksSummary(
            hosts = blocks.size,
            skipped = skipped,
        ),
    )
}

/** Appends the `Match` block of a host, and adds the key files it names to [files]. */
private fun StringBuilder.appendSshBookmarkBlock(
    key: SshBookmark,
    identities: List<SshBookmarkIdentity>,
    certificates: List<SshBookmarkCertificate>,
    directoryPath: String,
    identityAgentPath: String?,
    files: MutableMap<String, String>,
) {
    append("Match host ")
    append(key.host)
    if (key.user != null) {
        append(" user ")
        append(key.user)
    }
    appendLine()
    identities.forEach { identity ->
        val fileName = "${identity.keySha256}.pub"
        files[fileName] = identity.publicKey + "\n"
        appendLine("  IdentityFile \"$directoryPath/$fileName\"")
    }
    // With IdentitiesOnly, OpenSSH uses a certificate of
    // the agent only if a certificate file names it.
    certificates.forEach { certificate ->
        val fileName = "${certificate.sha256}$SSH_CERTIFICATE_FILE_SUFFIX"
        files[fileName] = certificate.certificate + "\n"
        appendLine("  CertificateFile \"$directoryPath/$fileName\"")
    }
    appendLine("  IdentitiesOnly yes")
    if (identityAgentPath != null) {
        appendLine("  IdentityAgent \"$identityAgentPath\"")
    }
}

// OpenSSH has no escape for a quote in a quoted value, expands `${}`
// variables in paths, and reads a line break as the end of the value.
private val SSH_CONFIG_PATH_UNSUPPORTED_CHARS = setOf('"', '$', '\n', '\r')

/**
 * Converts the [path] into the form that an SSH configuration reads literally,
 * or returns `null` if it can not. OpenSSH expands `%` tokens in paths, and
 * accepts `/` as a separator on Windows.
 */
internal fun sshConfigPathOrNull(path: String): String? {
    if (path.isEmpty() || path.any { it in SSH_CONFIG_PATH_UNSUPPORTED_CHARS }) {
        return null
    }
    return path
        .replace('\\', '/')
        .replace("%", "%%")
}
