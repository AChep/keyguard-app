package com.artemchep.keyguard.common.service.sshagent.bookmarks

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertNull

class SshBookmarksConfigTest {
    private val personal = identity(sha = "a".repeat(64), publicKey = "ssh-ed25519 AAAApersonal")
    private val work = identity(sha = "b".repeat(64), publicKey = "ssh-ed25519 AAAAwork")
    private val deploy = identity(sha = "c".repeat(64), publicKey = "ssh-rsa AAAAdeploy")
    private val certified = identity(
        sha = "d".repeat(64),
        publicKey = "ssh-ed25519 AAAAcertified",
        certificate = SshBookmarkCertificate(
            sha256 = "e".repeat(64),
            certificate = "ssh-ed25519-cert-v01@openssh.com AAAAcert",
        ),
    )

    private val entries = listOf(
        entry("ssh://git@github.com", personal, sortKey = "GitHub personal"),
        entry("ssh://git@GitHub.com/", work, sortKey = "GitHub work"),
        entry("ssh://deploy@build.example.com:2222", deploy, sortKey = "Build deploy"),
        entry("ssh://build.example.com", certified, sortKey = "Build CA"),
        entry("ssh://root@[2001:DB8::1]:22", deploy, sortKey = "Router"),
        entry("ssh://nas", personal, sortKey = "NAS"),
    )

    @Test
    fun `pins each host to its keys`() {
        val config = renderSshBookmarksConfig(
            entries = entries,
            skipped = 2,
            directory = "~/.ssh/keyguard",
            identityAgent = "/Users/me/.keyguard/ssh-agent.sock",
        )

        val agent = "  IdentityAgent \"/Users/me/.keyguard/ssh-agent.sock\""
        val expected = """
            # Generated by Keyguard from the ssh:// fields of SSH key items.
            # Keyguard replaces this file, so edit the items instead.

            Match host 2001:db8::1 user root
              IdentityFile "~/.ssh/keyguard/${deploy.keySha256}.pub"
              IdentitiesOnly yes
            $agent

            Match host build.example.com user deploy
              IdentityFile "~/.ssh/keyguard/${deploy.keySha256}.pub"
              IdentitiesOnly yes
            $agent

            Match host build.example.com
              IdentityFile "~/.ssh/keyguard/${certified.keySha256}.pub"
              CertificateFile "~/.ssh/keyguard/${"e".repeat(64)}-cert.pub"
              IdentitiesOnly yes
            $agent

            Match host github.com user git
              IdentityFile "~/.ssh/keyguard/${personal.keySha256}.pub"
              IdentityFile "~/.ssh/keyguard/${work.keySha256}.pub"
              IdentitiesOnly yes
            $agent

            Match host nas
              IdentityFile "~/.ssh/keyguard/${personal.keySha256}.pub"
              IdentitiesOnly yes
            $agent

        """.trimIndent()
        assertEquals(expected, config.files[SSH_BOOKMARKS_CONFIG_FILE_NAME])
        assertEquals(
            mapOf(
                "${personal.keySha256}.pub" to "ssh-ed25519 AAAApersonal\n",
                "${work.keySha256}.pub" to "ssh-ed25519 AAAAwork\n",
                "${deploy.keySha256}.pub" to "ssh-rsa AAAAdeploy\n",
                "${certified.keySha256}.pub" to "ssh-ed25519 AAAAcertified\n",
                "${"e".repeat(64)}-cert.pub" to "ssh-ed25519-cert-v01@openssh.com AAAAcert\n",
            ),
            config.files - SSH_BOOKMARKS_CONFIG_FILE_NAME,
        )
        assertEquals(5, config.summary.hosts)
        assertEquals(2, config.summary.skipped)
    }

    @Test
    fun `renders the same config for any order of entries`() {
        fun render(entries: List<SshBookmarkEntry>) = renderSshBookmarksConfig(
            entries = entries,
            skipped = 0,
            directory = "~/.ssh/keyguard",
            identityAgent = null,
        )

        assertEquals(render(entries), render(entries.reversed()))
    }

    @Test
    fun `lists a key once per host`() {
        val config = renderSshBookmarksConfig(
            entries = listOf(
                entry("ssh://git@github.com", personal, sortKey = "A"),
                entry("ssh://git@github.com:22", personal, sortKey = "B"),
            ),
            skipped = 0,
            directory = "~/.ssh/keyguard",
            identityAgent = null,
        )

        val text = config.files.getValue(SSH_BOOKMARKS_CONFIG_FILE_NAME)
        assertEquals(1, Regex("IdentityFile").findAll(text).count())
        assertEquals(1, config.summary.hosts)
    }

    @Test
    fun `keeps the certificate of an item that shares a key`() {
        val uncertified = certified.copy(certificate = null)
        val config = renderSshBookmarksConfig(
            entries = listOf(
                entry("ssh://build.example.com", uncertified, sortKey = "A"),
                entry("ssh://build.example.com", certified, sortKey = "B"),
            ),
            skipped = 0,
            directory = "~/.ssh/keyguard",
            identityAgent = null,
        )

        val text = config.files.getValue(SSH_BOOKMARKS_CONFIG_FILE_NAME)
        assertEquals(1, Regex("IdentityFile").findAll(text).count())
        assertEquals(1, Regex("CertificateFile").findAll(text).count())
        assertEquals(
            "ssh-ed25519-cert-v01@openssh.com AAAAcert\n",
            config.files["${"e".repeat(64)}-cert.pub"],
        )
    }

    @Test
    fun `writes no block without a key`() {
        val config = renderSshBookmarksConfig(
            entries = emptyList(),
            skipped = 3,
            directory = "~/.ssh/keyguard",
            identityAgent = "/tmp/agent.sock",
        )

        val text = config.files.getValue(SSH_BOOKMARKS_CONFIG_FILE_NAME)
        assertEquals(listOf(SSH_BOOKMARKS_CONFIG_FILE_NAME), config.files.keys.toList())
        assertNull(Regex("Match|IdentitiesOnly").find(text))
        assertEquals(0, config.summary.hosts)
        assertEquals(3, config.summary.skipped)
    }

    @Test
    fun `escapes paths for the config`() {
        val config = renderSshBookmarksConfig(
            entries = listOf(entry("ssh://example.com", personal, sortKey = "A")),
            skipped = 0,
            directory = "C:\\Users\\100%\\.ssh\\keyguard\\",
            identityAgent = "\\\\.\\pipe\\keyguard-ssh-agent",
        )

        val text = config.files.getValue(SSH_BOOKMARKS_CONFIG_FILE_NAME)
        assertEquals(
            listOf(
                "  IdentityFile \"C:/Users/100%%/.ssh/keyguard/${personal.keySha256}.pub\"",
                "  IdentityAgent \"//./pipe/keyguard-ssh-agent\"",
            ),
            text.lines().filter { "Identity" in it && "Only" !in it },
        )
    }

    @Test
    fun `leaves out an agent path that the config can not hold`() {
        val config = renderSshBookmarksConfig(
            entries = listOf(entry("ssh://example.com", personal, sortKey = "A")),
            skipped = 0,
            directory = "~/.ssh/keyguard",
            identityAgent = "\${HOME}/agent.sock",
        )

        val text = config.files.getValue(SSH_BOOKMARKS_CONFIG_FILE_NAME)
        assertNull(Regex("IdentityAgent").find(text))
    }

    @Test
    fun `rejects a directory that the config can not hold`() {
        assertFailsWith<IllegalArgumentException> {
            renderSshBookmarksConfig(
                entries = emptyList(),
                skipped = 0,
                directory = "/home/\"me\"/.ssh/keyguard",
                identityAgent = null,
            )
        }
    }

    private fun identity(
        sha: String,
        publicKey: String,
        certificate: SshBookmarkCertificate? = null,
    ) = SshBookmarkIdentity(
        keySha256 = sha,
        publicKey = publicKey,
        certificate = certificate,
    )

    private fun entry(
        url: String,
        identity: SshBookmarkIdentity,
        sortKey: String,
    ) = SshBookmarkEntry(
        bookmark = requireNotNull(parseSshBookmark(url)) { url },
        identity = identity,
        sortKey = sortKey,
    )
}
