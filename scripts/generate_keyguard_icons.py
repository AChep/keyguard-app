def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files or aliases are out of date")
    args = parser.parse_args()
    icons = read_icons()
    aliases = (KOTLIN / "Icons.kt").read_text()
    names = {icon["name"] for icon in icons}
    actual = set(re.findall(r"KeyguardVectors\.(\w+)", aliases))
    if actual != names:
        raise ValueError(f"SVG/alias mismatch: missing SVGs={actual - names}, missing aliases={names - actual}")
    for name in names:
        pattern = rf"val Icons\.Outlined\.Keyguard{name}: ImageVector\s+get\(\) = KeyguardVectors\.{name}\b"
        if not re.search(pattern, aliases):
            raise ValueError(f"Keyguard{name} must use its own generated vector")
    outputs = {
        KOTLIN / "KeyguardVectors.kt": compose_vectors(icons),
        ARTWORK / "preview.html": preview(icons),
    }
    stale = []
    for output, content in outputs.items():
        if args.check:
            if not output.exists() or output.read_text() != content:
                stale.append(str(output.relative_to(ROOT)))
        else:
            output.write_text(content)
    if stale:
        sys.exit("Regenerate the icon files: " + ", ".join(stale))
    print(f"{'Checked' if args.check else 'Generated'} {len(icons)} custom icons and the preview; every custom vector matches its alias.")


if __name__ == "__main__":
    main()
