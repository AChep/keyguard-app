ROOT = Path(__file__).resolve().parents[1]
ARTWORK = ROOT / "artwork/icons"
KOTLIN = ROOT / "common/src/commonMain/kotlin/com/artemchep/keyguard/ui/icons"
SVG = "{http://www.w3.org/2000/svg}"
NAVIGATION = {"GpgKey", "GpgKeySelected"}


def settings_icon_names():
    sources = list((ROOT / "common/src").glob("**/feature/home/settings/**/*.kt"))
    sources += list((ROOT / "wearApp/src").glob("**/feature/settings/**/*.kt"))
    sources += list((ROOT / "common/src").glob("**/feature/webdav/*Settings*.kt"))
    return {
        name for source in sources
        for name in re.findall(r"Icons\.Outlined\.Keyguard(\w+)", source.read_text())
    }


def read_icons():
    icons = []
    defaults = {
        "width": "24", "height": "24", "viewBox": "0 0 24 24",
        "fill": "none", "stroke": "currentColor", "stroke-width": "2",
        "stroke-linecap": "round", "stroke-linejoin": "round",
    }
    for source in sorted(ARTWORK.glob("keyguard-*.svg")):
        root = ET.fromstring(source.read_text())
        if root.tag != SVG + "svg":
            raise ValueError(f"{source.name}: expected an SVG root")
        if any(root.get(key) != value for key, value in defaults.items()):
            raise ValueError(f"{source.name}: expected the 24 px, 2 px stroke icon grid")
        if set(root.attrib) - defaults.keys() - {"data-auto-mirror"}:
            raise ValueError(f"{source.name}: unsupported SVG attributes")
        if root.get("data-auto-mirror", "false") not in {"true", "false"}:
            raise ValueError(f"{source.name}: invalid mirroring flag")
        title = root.findtext(SVG + "title")
        if not title:
            raise ValueError(f"{source.name}: missing title")
        paths = []
        for child in root:
            if child.tag == SVG + "title":
                continue
            if child.tag != SVG + "path" or set(child.attrib) - {"d", "fill", "stroke"}:
                raise ValueError(f"{source.name}: only plain paths are supported")
            data = child.get("d", "")
            if not data or re.search(r"[^MmLlHhVvCcSsQqTtAaZz0-9.,+\-\s]", data):
                raise ValueError(f"{source.name}: invalid path data")
            fill = child.get("fill", root.get("fill"))
            stroke = child.get("stroke", root.get("stroke"))
            if fill not in {"none", "currentColor"} or stroke not in {"none", "currentColor"}:
                raise ValueError(f"{source.name}: icons must use currentColor")
            paths.append((data, fill, stroke))
        if not paths:
            raise ValueError(f"{source.name}: missing paths")
        name = "".join(part.title() for part in source.stem.split("-")[1:])
        icons.append({
            "name": name, "title": title, "source": source, "paths": paths,
            "mirror": root.get("data-auto-mirror", "false"),
        })
    if not icons:
        raise ValueError("No icon sources found")
    return icons


def compose_vectors(icons):
    lines = [
        "// Generated by scripts/generate_keyguard_icons.py. Edit artwork/icons/keyguard-*.svg instead.",
        "package com.artemchep.keyguard.ui.icons", "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.graphics.SolidColor",
        "import androidx.compose.ui.graphics.StrokeCap",
        "import androidx.compose.ui.graphics.StrokeJoin",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import androidx.compose.ui.graphics.vector.addPathNodes",
        "import androidx.compose.ui.unit.dp", "",
        "internal object KeyguardVectors {",
    ]
    for icon in icons:
        lines += [
            f'    val {icon["name"]}: ImageVector by lazy {{',
            f'        icon(name = "Keyguard{icon["name"]}", autoMirror = {icon["mirror"]}) {{',
        ]
        for data, fill, stroke in icon["paths"]:
            lines += [
                "            addPath(",
                f"                pathData = addPathNodes({json.dumps(data)}),",
                "                fill = " + ("null" if fill == "none" else "SolidColor(Color.Black)") + ",",
            ]
            if stroke != "none":
                lines += [
                    "                stroke = SolidColor(Color.Black),",
                    "                strokeLineWidth = 2f,",
                    "                strokeLineCap = StrokeCap.Round,",
                    "                strokeLineJoin = StrokeJoin.Round,",
                ]
            lines += ["            )"]
        lines += ["        }", "    }", ""]
    lines += [
        "    private fun icon(",
        "        name: String,",
        "        autoMirror: Boolean,",
        "        block: ImageVector.Builder.() -> Unit,",
        "    ): ImageVector = ImageVector.Builder(",
        "        name = name,",
        "        defaultWidth = 24.dp,",
        "        defaultHeight = 24.dp,",
        "        viewportWidth = 24f,",
        "        viewportHeight = 24f,",
        "        autoMirror = autoMirror,",
        "    ).apply(block).build()",
        "}", "",
    ]
    return "\n".join(lines)


def preview(icons):
    tiles = []
    settings = settings_icon_names()
    for icon in icons:
        artwork = icon["source"].read_text().strip()
        families = []
        if icon["name"].startswith("Gpg") or icon["name"] in {
            "Encrypt", "Decrypt", "FileSign", "FileVerify", "WeakGpgKey", "UnusableGpgKey",
        }:
            families.append("gpg")
        if icon["name"] in settings:
            families.append("settings")
        if icon["name"] in NAVIGATION:
            families.append("navigation")
        sizes = "".join(
            f'<span><span class="sample" style="--sample:{size}px">{artwork}</span><small>{size}</small></span>'
            for size in (12, 16, 20, 24)
        )
        tiles.append(
            f'<article data-family="{" ".join(families)}"><a class="glyph" href="{icon["source"].name}" aria-label="Open {html.escape(icon["title"])} SVG">{artwork}</a>'
            f'<h2>{html.escape(icon["title"])}</h2><code>Keyguard{icon["name"]}</code>'
            f'<div class="sizes" aria-hidden="true">{sizes}</div></article>'
        )
    return PREVIEW_HEAD.replace("ICON_COUNT", str(len(icons))) + '<section class="icons" aria-label="Icon gallery">' + "\n".join(tiles) + PREVIEW_FOOT


