use std::error::Error;
use std::ffi::OsString;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

const USAGE: &str =
    "usage: native-protocol <generate|check> <schema.proto> <generated-package.rs> <output.rs>";

fn main() {
    if let Err(error) = run(std::env::args_os().skip(1)) {
        eprintln!("ERROR: {error}");
        std::process::exit(1);
    }
}

fn run(args: impl IntoIterator<Item = OsString>) -> Result<(), Box<dyn Error>> {
    let args: Vec<_> = args.into_iter().collect();
    let [command, schema, generated_file, output] = args.as_slice() else {
        return Err(USAGE.into());
    };
    if !matches!(command.to_str(), Some("generate" | "check")) {
        return Err(USAGE.into());
    }
    let generated_file = Path::new(generated_file);
    if generated_file.file_name() != Some(generated_file.as_os_str()) {
        return Err("the generated package must be a file name".into());
    }
    let schema = Path::new(schema);
    let output = Path::new(output);
    let generated = generate(schema, generated_file)?;
    match command.to_str() {
        Some("generate") => write_generated(output, &generated),
        Some("check") => check_generated(output, &generated),
        _ => unreachable!(),
    }
}

fn generate(schema: &Path, generated_file: &Path) -> Result<String, Box<dyn Error>> {
    let schema_dir = schema
        .parent()
        .filter(|path| !path.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let output_dir = TemporaryDirectory::create()?;

    prost_build::Config::new()
        .out_dir(output_dir.path())
        .compile_protos(&[schema], &[schema_dir])?;

    let generated = fs::read_to_string(output_dir.path().join(generated_file))?;
    Ok(format!(
        "// @generated by native-protocol.\n// The source of truth is {}.\n\n{generated}",
        schema.display()
    ))
}

fn write_generated(output: &Path, generated: &str) -> Result<(), Box<dyn Error>> {
    if fs::read_to_string(output).ok().as_deref() == Some(generated) {
        println!("{} is already up to date.", output.display());
        return Ok(());
    }
    if let Some(parent) = output.parent().filter(|path| !path.as_os_str().is_empty()) {
        fs::create_dir_all(parent)?;
    }
    fs::write(output, generated)?;
    println!("Updated {}.", output.display());
    Ok(())
}

fn check_generated(output: &Path, generated: &str) -> Result<(), Box<dyn Error>> {
    match fs::read_to_string(output) {
        Ok(current) if current == generated => {
            println!("{} is up to date.", output.display());
            Ok(())
        }
        Ok(_) => Err(format!(
            "protocol drift detected in {}; regenerate it",
            output.display()
        )
        .into()),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Err(format!(
            "generated protocol is missing at {}; generate it",
            output.display()
        )
        .into()),
        Err(error) => Err(error.into()),
    }
}

struct TemporaryDirectory(PathBuf);

impl TemporaryDirectory {
    fn create() -> Result<Self, Box<dyn Error>> {
        let nonce = SystemTime::now().duration_since(UNIX_EPOCH)?.as_nanos();
        let path = std::env::temp_dir().join(format!(
            "keyguard-native-protocol-{}-{nonce}",
            std::process::id()
        ));
        fs::create_dir(&path)?;
        Ok(Self(path))
    }

    fn path(&self) -> &Path {
        &self.0
    }
}

impl Drop for TemporaryDirectory {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_and_checks_a_protocol_without_repository_paths() {
        let directory = TemporaryDirectory::create().unwrap();
        let schema = directory.path().join("example.proto");
        let output = directory.path().join("nested/output.rs");
        fs::write(
            &schema,
            "syntax = \"proto3\"; package example.v1; message Example { string name = 1; }",
        )
        .unwrap();
        let invoke = |command: &str| {
            run([
                OsString::from(command),
                schema.as_os_str().to_owned(),
                OsString::from("example.v1.rs"),
                output.as_os_str().to_owned(),
            ])
        };
        assert!(invoke("check").is_err());
        invoke("generate").unwrap();
        assert!(
            fs::read_to_string(&output)
                .unwrap()
                .contains("pub struct Example")
        );
        invoke("check").unwrap();
        fs::write(&output, "stale").unwrap();
        assert!(invoke("check").is_err());
        assert_eq!(fs::read_to_string(&output).unwrap(), "stale");
        invoke("generate").unwrap();
        invoke("check").unwrap();
    }

    #[test]
    fn rejects_bad_arguments_before_accessing_files() {
        assert!(run([]).is_err());
        assert!(
            run(["invalid", "missing.proto", "example.rs", "out.rs"].map(OsString::from)).is_err()
        );
        assert!(
            run(["generate", "missing.proto", "../example.rs", "out.rs"].map(OsString::from))
                .is_err()
        );
    }
}
